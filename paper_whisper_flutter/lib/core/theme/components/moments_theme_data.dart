import 'package:flutter/material.dart';

/// 瞬间页面 主题数据
class MomentsThemeData {
  final Color rulerBg;
  final Color rulerTextColor;
  final Color rulerInactiveTextColor;
  final Color rulerSubTextColor;
  final Color rulerInactiveSubTextColor;
  final Color rulerIndicatorColor;
  final Color rulerShadowColor;
  final Color rulerBorderColor;
  final Color appBarIconColor;
  final Color appBarTextColor;
  final Color drawerScrimColor;
  final Color appBarBg;
  final Color emptyStateIconColor;
  final Color emptyStateTextColor;

  const MomentsThemeData({
