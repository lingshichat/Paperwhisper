    required this.rulerTextColor,
    required this.rulerInactiveTextColor,
    required this.rulerSubTextColor,
    required this.rulerInactiveSubTextColor,
    required this.rulerIndicatorColor,
    required this.rulerShadowColor,
    required this.rulerBorderColor,
    required this.appBarIconColor,
    required this.appBarTextColor,
    required this.drawerScrimColor,
    required this.appBarBg,
    required this.emptyStateIconColor,
    required this.emptyStateTextColor,
  });
}
